#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
readonly SCRIPT_DIR
# shellcheck disable=SC1091
source "$SCRIPT_DIR/libexec/vpn-gateway-lib"
MODE=install
if [[ ${1:-} == --check ]]; then
    MODE=check
    shift
fi
readonly CONFIG_SOURCE="${1:-./vpn-gateway.conf}"

fail() {
    echo "ERROR: $*" >&2
    exit 1
}

require_root() {
    [[ $EUID -eq 0 ]] || fail "Run with sudo: sudo ./install.sh ./vpn-gateway.conf"
}

load_config() {
    [[ -f $CONFIG_SOURCE ]] || fail "Configuration not found: $CONFIG_SOURCE"
    # shellcheck disable=SC1090
    source "$CONFIG_SOURCE"
    local required=(APPLIANCE_USER UPLINK_CONNECTION UPLINK_INTERFACE DNS_SERVERS VPN_SERVER VPN_AUTHGROUP)
    required+=(VPN_USERNAME TUN_INTERFACE VPN_TARGETS OPENCONNECT_SAML_VERSION)
    local name
    for name in "${required[@]}"; do
        [[ -n ${!name:-} ]] || fail "Missing required setting: $name"
    done
    id "$APPLIANCE_USER" >/dev/null 2>&1 || fail "Linux user does not exist: $APPLIANCE_USER"
    # UPLINK_INTERFACE is loaded from the validated configuration file.
    # shellcheck disable=SC2153
    ip link show "$UPLINK_INTERFACE" >/dev/null 2>&1 || fail "Interface does not exist: $UPLINK_INTERFACE"
    nmcli connection show "$UPLINK_CONNECTION" >/dev/null 2>&1 || fail "Connection does not exist: $UPLINK_CONNECTION"
    [[ $VPN_SERVER =~ ^https://[^[:space:]]+$ ]] || fail "VPN_SERVER must be an HTTPS URL"
    [[ $TUN_INTERFACE =~ ^[a-zA-Z0-9_.:-]+$ ]] || fail "Invalid TUN_INTERFACE"
    [[ ${WRITE_STATIC_RESOLV_CONF:-false} =~ ^(true|false)$ ]] || fail "WRITE_STATIC_RESOLV_CONF must be true or false"
}

validate_targets() {
    local targets=()
    read_ipv4_targets "$VPN_TARGETS" targets || fail "VPN_TARGETS must contain valid IPv4 CIDR values"
}

install_packages() {
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y ca-certificates curl network-manager nftables openconnect pipx \
        python3-venv xterm
    local home
    home=$(getent passwd "$APPLIANCE_USER" | cut -d: -f6)
    sudo -H -u "$APPLIANCE_USER" env PIPX_HOME="$home/.local/share/pipx" PIPX_BIN_DIR="$home/.local/bin" \
        pipx install --force "openconnect-saml[gui]==$OPENCONNECT_SAML_VERSION"
}

install_config() {
    install -o root -g root -m 0644 "$CONFIG_SOURCE" /etc/vpn-gateway.conf
    install -o root -g root -m 0755 "$SCRIPT_DIR/bin/vpn-gateway" /usr/local/bin/vpn-gateway
    install -o root -g root -m 0755 "$SCRIPT_DIR/libexec/vpn-gateway-router" \
        /usr/local/libexec/vpn-gateway-router
    install -o root -g root -m 0644 "$SCRIPT_DIR/libexec/vpn-gateway-lib" \
        /usr/local/libexec/vpn-gateway-lib
    install -o root -g root -m 0644 "$SCRIPT_DIR/systemd/vpn-gateway-router.service" \
        /etc/systemd/system/vpn-gateway-router.service
    install -o root -g root -m 0644 "$SCRIPT_DIR/sysctl/90-vpn-gateway.conf" \
        /etc/sysctl.d/90-vpn-gateway.conf
    /usr/local/libexec/vpn-gateway-router check
}

configure_network() {
    # DNS_SERVERS is loaded from the validated configuration file.
    # shellcheck disable=SC2153
    local dns_csv=${DNS_SERVERS// /,}
    local state_dir=/var/lib/vpn-gateway
    local args=(connection modify "$UPLINK_CONNECTION" connection.interface-name "$UPLINK_INTERFACE")
    args+=(connection.autoconnect yes connection.autoconnect-priority 100 ipv4.dns "$dns_csv")
    args+=(ipv4.ignore-auto-dns yes)
    if [[ -n ${UPLINK_MAC:-} && $UPLINK_MAC != "00:00:00:00:00:00" ]]; then
        args+=(802-3-ethernet.mac-address "$UPLINK_MAC")
    fi
    nmcli "${args[@]}"
    if [[ ${WRITE_STATIC_RESOLV_CONF:-false} == true ]]; then
        install -d -o root -g root -m 0700 "$state_dir"
        if [[ ! -e $state_dir/resolv.conf.original && ! -L $state_dir/resolv.conf.original ]]; then
            cp -a --no-dereference /etc/resolv.conf "$state_dir/resolv.conf.original"
        fi
        rm -f /etc/resolv.conf
        : > /etc/resolv.conf
        local server
        local dns_servers=()
        read -r -a dns_servers <<< "$DNS_SERVERS"
        for server in "${dns_servers[@]}"; do
            printf 'nameserver %s\n' "$server" >> /etc/resolv.conf
        done
        chmod 0644 /etc/resolv.conf
    fi
    nmcli connection up "$UPLINK_CONNECTION" ifname "$UPLINK_INTERFACE"
}

install_privileges() {
    local sudoers=/etc/sudoers.d/90-vpn-gateway
    {
        echo "# Generated by vpn-gateway installer for a dedicated VM."
        echo "$APPLIANCE_USER ALL=(root) NOPASSWD: /usr/sbin/openconnect *"
        printf '%s ALL=(root) NOPASSWD: /usr/bin/nmcli connection up %s ifname %s\n' \
            "$APPLIANCE_USER" "$UPLINK_CONNECTION" "$UPLINK_INTERFACE"
        echo "$APPLIANCE_USER ALL=(root) NOPASSWD: /usr/sbin/nft list table inet vpn_gateway"
    } > "$sudoers"
    chmod 0440 "$sudoers"
    visudo -cf "$sudoers"
}

install_launcher() {
    local home desktop
    home=$(getent passwd "$APPLIANCE_USER" | cut -d: -f6)
    desktop="$home/Desktop"
    install -d -o "$APPLIANCE_USER" -g "$APPLIANCE_USER" -m 0755 "$desktop"
    sed "s|@HOME@|$home|g" "$SCRIPT_DIR/desktop/vpn-gateway.desktop" > "$desktop/VPN Gateway.desktop"
    chown "$APPLIANCE_USER:$APPLIANCE_USER" "$desktop/VPN Gateway.desktop"
    chmod 0755 "$desktop/VPN Gateway.desktop"
}

enable_services() {
    sysctl --system >/dev/null
    systemctl daemon-reload
    systemctl enable --now vpn-gateway-router.service
}

main() {
    [[ $MODE == check ]] || require_root
    load_config
    validate_targets
    if [[ $MODE == check ]]; then
        echo "Configuration is valid for this machine. No changes were made."
        exit 0
    fi
    install_packages
    install_config
    configure_network
    install_privileges
    install_launcher
    enable_services
    echo "Installed successfully. Run as $APPLIANCE_USER: vpn-gateway connect"
}

main "$@"
